/*
 * A GPIO wake generated by erpc_wifi_ensure_awake_tx() is HOST-initiated.
 *
 * The SRDY rising edge caused by that wake must not be consumed by the
 * autonomous socket-event path.  Without this ownership marker the poll
 * task can race the TX wake path, misclassify a FAST wake as autonomous,
 * issue GET_SOCKET_EVT, and steal/perturb the SRDY handshake that the TX
 * caller is waiting for.
 */
static atomic_t g_host_wake_inflight;

