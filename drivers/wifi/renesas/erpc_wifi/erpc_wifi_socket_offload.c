static void erpc_wifi_srdy_deferred_work(struct k_work *work)
{
	ARG_UNUSED(work);

	/*
	 * During an explicit host GPIO wake, SRDY activity belongs to the host
	 * wake/eRPC handshake.  Do not turn that response into an autonomous
	 * socket wake after the eRPC completes.
	 */
	if (atomic_get(&g_host_wake_inflight) != 0) {
		atomic_set(&g_srdy_deferred, 0);
		return;
	}

	/* Another host eRPC started. Check after it completes. */
	if (atomic_get(&g_host_erpc_inflight) != 0) {
		k_work_reschedule(&g_srdy_deferred_work, K_MSEC(5));
		return;
	}

	/*
	 * Never carry the SLEEP_PROHIBITED REMOVE response
	 * across the sleep-entry guard.
	 */
	if (erpc_wifi_ps_is_enabled() &&
	    erpc_wifi_ps_wait_for_srdy_low_get()) {

		atomic_set(&g_srdy_deferred, 0);
		return;
	}

	if (!atomic_cas(&g_srdy_deferred, 1, 0)) {
		return;
	}

	if (erpc_wifi_transport_slave_ready()) {
		atomic_set(&g_srdy_irq_pending, 1);
	}

	/*
	 * Even if SRDY already fell, do one socket-event recovery pass.
	 * This is NOT treated as autonomous wake unless SRDY is actually high.
	 */
	k_sem_give(&poll_task_sem);
}

void erpc_wifi_offload_server_evt_query_begin(void)
{
	atomic_set(&g_server_evt_query_inflight, 1);
}

void erpc_wifi_offload_server_evt_query_end(void)
{
	atomic_set(&g_server_evt_query_inflight, 0);
}

void erpc_wifi_offload_host_erpc_begin(void)
{
	atomic_set(&g_host_erpc_inflight, 1);
}

void erpc_wifi_offload_host_erpc_end(void)
{
	atomic_set(&g_host_erpc_inflight, 0);

	if (atomic_get(&g_srdy_deferred) != 0) {
		k_work_reschedule(&g_srdy_deferred_work, K_MSEC(5));
	}
}
static void erpc_wifi_socket_poll_task(void *arg1, void *arg2, void *arg3)
{
	ARG_UNUSED(arg1);
	ARG_UNUSED(arg2);
	ARG_UNUSED(arg3);
	int64_t last_not_ready_log = 0;
	int last_srdy_level = erpc_wifi_transport_slave_ready();

	while (1) {
		/*
		 * Customer-stable servicing semantics:
		 *   - an active socket waiter is revisited every 200 ms;
		 *   - a filtered DPM TCP socket gets a 500 ms fallback pass.
		 *
		 * The timeout only services sockets while the module is already awake.
		 * It does NOT wake a genuinely sleeping RA6W1.
		 */
		bool waiter_polling_needed = false;
		bool dpm_polling_needed = false;

		for (int i = 0; i < ERPC_WIFI_MAX_SOCKETS; i++) {
			if (!sockets[i].in_use) {
				continue;
			}

			if (sockets[i].waiting || sockets[i].connect_pending) {
				waiter_polling_needed = true;
			}

			if (erpc_wifi_ps_is_enabled() &&
			    sockets[i].type == SOCK_STREAM &&
			    sockets[i].tcp_dpm_filter_set) {
				dpm_polling_needed = true;
			}
		}

		k_timeout_t wait_timeout =
			waiter_polling_needed ? K_MSEC(200) :
			(dpm_polling_needed ? K_MSEC(500) : K_FOREVER);

		int wait_rc = k_sem_take(&poll_task_sem, wait_timeout);
		bool fallback_timeout = (wait_rc != 0);
		bool dpm_timeout = fallback_timeout && !waiter_polling_needed && dpm_polling_needed;

		/*
		 * An explicit host TX wake owns SRDY until ensure_awake_tx() has
		 * completed.  Do not consume/classify its rising edge here.
		 * Also absorb the sampled level so the host-generated rise cannot
		 * later be reconstructed as a missed autonomous edge.
		 */
		if (atomic_get(&g_host_wake_inflight) != 0) {
			last_srdy_level = erpc_wifi_transport_slave_ready();
			k_msleep(5);
			continue;
		}

		int srdy_level = erpc_wifi_transport_slave_ready();
		bool sampled_srdy_rise = (last_srdy_level == 0 && srdy_level == 1);
		last_srdy_level = srdy_level;

		/*
		 * Normally the ISR supplies the edge.  The sampled 0->1 transition is
		 * a constrained recovery for a genuinely missed/coalesced IRQ; unlike
		 * a static-SRDY-HIGH fallback it still requires an observed transition.
		 */
		bool srdy_irq = atomic_cas(&g_srdy_irq_pending, 1, 0) || sampled_srdy_rise;

		/* Skip polling if WiFi interface is not connected */
		if (erpc_wifi_driver_data.state != WIFI_STATE_COMPLETED) {
			k_msleep(100);
			continue;
		}

#if defined(CONFIG_NET_IPV4)
		if (erpc_wifi_ps_is_enabled() && !erpc_wifi_driver_data.ipv4_assigned) {
			k_msleep(50);
			continue;
		}
#endif

		bool ps_enabled = erpc_wifi_ps_is_enabled();
		bool module_asleep =
			ps_enabled &&
			erpc_wifi_ps_is_module_asleep();

		if (erpc_wifi_ps_is_enabled() && erpc_wifi_ps_wait_for_srdy_low_get()) {
			/*
			 * IMPORTANT:
			 * Ignore SRDY edges during the sleep-entry quiet window.
			 *
			 * SLEEP_PROHIBITED REMOVE itself generates normal
			 * SPI/eRPC SRDY activity. That edge must NOT later be
			 * interpreted as an autonomous DPM/socket wake.
			 */
			k_msleep(20);
			continue;
		}

		/*
		 * Release candidate: autonomous DPM wake qualification is edge based.
		 * A host-generated FAST wake is suppressed by g_host_wake_inflight;
		 * a real/deferred asynchronous SRDY edge remains the UC event source.
		 */
		bool autonomous_pass =
			module_asleep &&
			srdy_irq;

		bool autonomous_started = false;

		if (autonomous_pass) {
			/*
			 * Let the RA6W1 finish UC wake + RTM socket restore first.
			 * Do not send any PMGR command during this interval.
			 */
			k_msleep(150);

			if (!erpc_wifi_transport_slave_ready()) {
				LOG_DBG("Ignoring stale autonomous SRDY");
				continue;
			}

			/*
			 * Freeze normal host eRPC producers in WAKING_UP, but do not
			 * claim SLEEP_PROHIBITED yet.  GET_SOCKET_EVT must be the first
			 * host transaction after an RA-originated UC wake.
			 */
			autonomous_started =
				erpc_wifi_ps_begin_autonomous_wakeup();

			if (!autonomous_started) {
				/*
				 * Another host wake path won the race.  Let that path finish;
				 * a waiting socket will be revisited by the normal poll pass.
				 */
				continue;
			}
		}

		for (int i = 0; i < ERPC_WIFI_MAX_SOCKETS; i++) {
			struct erpc_wifi_socket *sock = &sockets[i];

			if (!sock->in_use) {
				continue;
			}

			bool waiter_probe = sock->waiting || sock->connect_pending;

			/*
			 * One real autonomous wake may belong to ANY filtered
			 * TCP socket. Query all of them once.
			 */
			bool dpm_event_probe =
				autonomous_pass &&
				sock->type == SOCK_STREAM &&
				(sock->tcp_dpm_filter_set || sock->connect_pending);

			/*
			 * Restore the customer-stable missed-edge fallback: on the 500 ms
			 * servicing timeout, re-query a filtered TCP socket if the host PS
			 * state already says RA6W1 is awake.  Never turn this timeout into a
			 * wake request while the module is genuinely asleep.
			 */
			bool filtered_tcp =
				sock->type == SOCK_STREAM &&
				(sock->tcp_dpm_filter_set || sock->connect_pending);

			/*
			 * Match the customer-stable scanner more closely:
			 * - while PS is disabled, a 200 ms waiter tick services only waiters;
			 *   it must not scan unrelated filtered sockets;
			 * - while PS is enabled and RA is already awake, a real SRDY IRQ may
			 *   query all filtered TCP sockets; the periodic filtered-socket fallback
			 *   remains 500 ms and does not collapse to 200 ms because another socket
			 *   happens to have an active waiter.
			 */
			bool awake_irq_probe =
				ps_enabled &&
				srdy_irq &&
				!module_asleep &&
				filtered_tcp;

			bool awake_fallback_probe =
				ps_enabled &&
				dpm_timeout &&
				!module_asleep &&
				filtered_tcp;

			if (!waiter_probe && !dpm_event_probe &&
			    !awake_irq_probe && !awake_fallback_probe) {
				continue;
			}

			/*
			 * Never let ensure_awake_rx() wait forever for an AWAKE
			 * transition that the poll task itself has not established.
			 */
			if (erpc_wifi_ps_is_enabled() &&
			    !autonomous_started &&
			    !erpc_wifi_ps_is_module_awake()) {
				continue;
			}

			int srdy = erpc_wifi_transport_slave_ready();

			if (!srdy && !dpm_event_probe) {
				bool pollout_probe =
					waiter_probe &&
					((sock->poll_events & ZVFS_POLLOUT) || sock->connect_pending);

				bool irq_wait_probe =
					waiter_probe && srdy_irq;

				/*
				 * Customer-stable code services an awake waiter even when SRDY has
				 * already fallen after the previous eRPC. ensure_awake_rx() below
				 * reasserts SRDY for the query. This is the missing 200 ms retry
				 * behavior needed by TLS/MQTT waiters.
				 */
				bool awake_waiter_probe = waiter_probe && !module_asleep;

				if (!pollout_probe && !irq_wait_probe &&
				    !awake_waiter_probe && !awake_fallback_probe) {
					continue;
				}
			}

			/*
			 * IMPORTANT: GET_SOCKET_EVT is only an event inspection.  Do not
			 * acquire POWER_RAM for every 200/500 ms poll pass.  Doing so turns
			 * one MQTT/TLS waiter into a stream of PMGR ADD_SLEEP_CONSTRAINT
			 * commands and can starve real send/recv/socket-create traffic.
			 *
			 * This matches the customer-stable ownership model: if RA is already
			 * awake but SRDY has fallen after the previous SPI transaction, issue
			 * only a short host wake pulse to reassert SRDY.  Real recv/send paths
			 * still acquire/release POWER_RAM through ensure_awake_rx/tx().
			 *
			 * Autonomous RA-originated wake is already ready for its first
			 * GET_SOCKET_EVT and must not be host-pulsed here.
			 */
			if (!autonomous_started && ps_enabled) {
				if (!erpc_wifi_ps_is_module_awake()) {
					continue;
				}

				if (!erpc_wifi_transport_slave_ready()) {
					/* Own only this explicit poll re-pulse so its SRDY edge is not
					 * reconstructed as an autonomous wake.  If another host wake
					 * already owns the line, defer this poll pass. */
					if (!atomic_cas(&g_host_wake_inflight, 0, 1)) {
						continue;
					}

					erpc_wifi_gpio_wakeup_pulse_fast();

					int64_t deadline = k_uptime_get() + 300;
					while (!erpc_wifi_transport_slave_ready() &&
					       k_uptime_get() < deadline) {
						k_msleep(5);
					}

					bool ready = erpc_wifi_transport_slave_ready();
					atomic_set(&g_host_wake_inflight, 0);

					if (!ready) {
						continue;
					}

					/* Absorb our own sampled 0->1 level so the next loop cannot
					 * reinterpret the poll re-pulse as an autonomous SRDY edge. */
					last_srdy_level = 1;
				}
			}

			int ev_fd = sock->fd;

			atomic_set(&g_socket_evt_query_inflight, 1);

			uint32_t events =
				(uint32_t)erpc_wifi_send_cmd(
				EPRC_WIFI_GET_SOCKET_EVT_CMD,
				&ev_fd,
				sizeof(ev_fd), -1);

			atomic_set(&g_socket_evt_query_inflight, 0);

			if (events == UINT32_MAX) {
				LOG_DBG("poll get_socket_events failed fd=%d; deferring", sock->fd);
				continue;
			}

			bool notify_connected = false;
			bool notify_failed = false;
			int log_connected_fd = -1;
			int log_failed_fd = -1;

			k_spinlock_key_t key = k_spin_lock(&sock->state_lock);
			uint32_t all_events = events & (SOCKET_EVENT_RX | SOCKET_EVENT_TX | SOCKET_EVENT_ERR | SOCKET_EVENT_CLOSE);
			sock->triggered_events |= (short)all_events;

			if (sock->connect_pending) {
				if (events & SOCKET_EVENT_TX) {
					sock->connect_pending = false;
					sock->connected = true;
					sock->socket_error = 0;
					notify_connected = true;
					log_connected_fd = sock->fd;
				} else if (events & (SOCKET_EVENT_ERR | SOCKET_EVENT_CLOSE)) {
					sock->connect_pending = false;
					sock->connected = false;
					sock->socket_error = -1;
					notify_failed = true;
					log_failed_fd = sock->fd;
				}
			}

			uint32_t requested_mask = 0;
			if (sock->poll_events & ZVFS_POLLIN) {
				requested_mask |= SOCKET_EVENT_RX;
			}
			if (sock->poll_events & ZVFS_POLLOUT) {
				requested_mask |= SOCKET_EVENT_TX;
			}
			requested_mask |= SOCKET_EVENT_ERR | SOCKET_EVENT_CLOSE;

			uint32_t ready = sock->triggered_events & requested_mask;
			bool do_signal = false;

			if (sock->waiting && ready != 0) {
				sock->waiting = false;
				do_signal = true;
			}
			k_spin_unlock(&sock->state_lock, key);

			if (notify_connected) {
				erpc_wifi_ps_notify_socket_connected();
				LOG_DBG("Non-blocking connect completed for fd %d", log_connected_fd);
			}
			if (notify_failed) {
				erpc_wifi_ps_notify_socket_connect_failed();
				LOG_WRN("Non-blocking connect failed for fd %d", log_failed_fd);
			}

			if (do_signal) {
				k_poll_signal_raise(&sock->poll_signal, (int)ready);
			}
		}

		/*
		 * Release application/event-monitor waiters only after every restored
		 * DPM TCP socket has had one GET_SOCKET_EVT query.
		 */
		if (autonomous_started) {
			erpc_wifi_ps_finish_autonomous_wakeup();
		}
	}
}

static void ensure_poll_task_started(void)
{
	if (erpc_wifi_socket_poll_tid != NULL) {
		return;
	}

	erpc_wifi_socket_poll_tid = k_thread_create(
		&erpc_wifi_socket_poll_thread_data, erpc_wifi_socket_poll_stack,
		K_THREAD_STACK_SIZEOF(erpc_wifi_socket_poll_stack), erpc_wifi_socket_poll_task,
		NULL, NULL, NULL, K_PRIO_PREEMPT(7), 0, K_NO_WAIT);
	k_thread_name_set(erpc_wifi_socket_poll_tid, "erpc_socket_poll");
}
