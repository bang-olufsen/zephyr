static int pmgr_dpm_cached_enabled(void)
{
	static int cached = -1;

	if (cached >= 0) {
		return cached;
	}

	int32_t en = (int32_t)erpc_wifi_send_cmd(ERPC_WIFI_PMGR_DPM_IS_ENABLED_CMD, NULL, 0, -1);
	cached = (en == 1) ? 1 : 0;
	return cached;
}

static inline int pmgr_ram_hold(void)
{
	if (pmgr_dpm_cached_enabled()) {
		int32_t rc = -1;
		for (int i = 0; i < 5; i++) {
			erpc_wifi_pmgr_constraint_t cstr = { .constraint = PMGR_CONSTRAINT_POWER_RAM };
			rc = (int32_t)erpc_wifi_send_cmd(ERPC_WIFI_PMGR_ADD_SLEEP_CONSTRAINT_CMD,
											  &cstr, sizeof(cstr), -1);
			if (rc >= 0) {
				break;
			}
			/* Transient SPI CRC error (err 8) is common on the first frame after DPM wake due to
			 * hardware synchronization. Retry. */
			k_msleep(10);
		}
		if (rc < 0) {
			LOG_ERR("pmgr_ram_hold failed: %d", rc);
			return rc;
		}
	}

	return 0;
}

int erpc_wifi_pmgr_ram_release(uint32_t job_id)
{
	if (pmgr_dpm_cached_enabled()) {
		int32_t rc = -1;
		for (int i = 0; i < 5; i++) {
			erpc_wifi_pmgr_constraint_t cstr = { .constraint = PMGR_CONSTRAINT_POWER_RAM };
			rc = (int32_t)erpc_wifi_send_cmd(ERPC_WIFI_PMGR_REMOVE_SLEEP_CONSTRAINT_CMD,
											  &cstr, sizeof(cstr), -1);
			if (rc >= 0) {
				break;
			}
			k_msleep(10);
		}
		if (rc < 0) {
			LOG_ERR("pmgr_ram_release failed: %d", rc);
			return rc;
		}
		if (job_id != 0) {
			erpc_wifi_pmgr_job_t job_msg = { .job_id = job_id };
			(void)erpc_wifi_send_cmd(ERPC_WIFI_PMGR_DPM_WAKEUP_DONE_CMD,
								   &job_msg, sizeof(job_msg), -1);
		}
	}
	return 0;
}

/*
 * erpc_wifi_wake_for_tx - exported wrapper for callers outside this file
 * (e.g. DNS offload) that need to perform a host-initiated eRPC operation
 * while the RA6W1 may be in DPM sleep.
 */
int erpc_wifi_wake_for_tx(void)
{
	bool ram_held = false;
	int ret = erpc_wifi_ensure_awake_tx(ERPC_PMGR_JOB_ID_SEND, &ram_held);
	if (ret < 0) {
		if (ram_held) {
			(void)erpc_wifi_pmgr_ram_release(ERPC_PMGR_JOB_ID_SEND);
		}
	}
	return ret;
}

/*
 * Ownership-safe variant for non-socket callers such as DNS.
 * On success, *ram_held tells the caller whether it owns a POWER_RAM
 * reference that must be released exactly once after the eRPC sequence.
 */
int erpc_wifi_wake_for_tx_acquire(bool *ram_held)
{
	if (ram_held == NULL) {
		return -EINVAL;
	}

	*ram_held = false;

	int ret =
		erpc_wifi_ensure_awake_tx(
			ERPC_PMGR_JOB_ID_SEND,
			ram_held);

	if (ret < 0 && *ram_held) {
		(void)erpc_wifi_pmgr_ram_release(
			ERPC_PMGR_JOB_ID_SEND);
		*ram_held = false;
	}

	return ret;
}

